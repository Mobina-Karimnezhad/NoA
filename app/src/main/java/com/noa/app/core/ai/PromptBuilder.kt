package com.noa.app.core.ai

import com.noa.app.domain.model.Habit
import com.noa.app.domain.model.WeekDay

object PromptBuilder {

    fun buildAdvisorPrompt(

        habits: List<Habit>,

        focusArea: String,

        occupation: String,

        ageGroup: String,

        busyDays: List<WeekDay>,

        extraDetails: String

    ): String {

        val habitsList =
            habits.joinToString(separator = "\n") {
                "id=${it.id} -> ${it.title} (${it.description})"
            }

        val busyDaysList =
            if (busyDays.isEmpty())
                "هیچ روز مشخصی"
            else
                busyDays.joinToString(", ") { it.name }

        val extraDetailsText =
            if (extraDetails.isBlank())
                "توضیح اضافه‌ای نداده."
            else
                extraDetails.trim()

        return """
تو یک مشاور عادت‌سازی هستی. با توجه به اطلاعات زیر، دقیقاً یکی از عادت‌های موجود را با تنظیمات مناسب و شخصی‌سازی‌شده پیشنهاد بده.

توجه فرهنگی مهم: کاربر ایرانی و فارسی‌زبان است. هفته از شنبه آغاز می‌شود (ترتیب: شنبه، یکشنبه، دوشنبه، سه‌شنبه، چهارشنبه، پنجشنبه، جمعه) و روزهای تعطیل رسمی در ایران پنجشنبه و جمعه هستند، نه شنبه و یکشنبه. هرگز شنبه یا یکشنبه را «آخر هفته» یا «روز تعطیل» در نظر نگیر و در تحلیل‌ها و دلیل‌ها (reason) هم به این تقویم پایبند باش.

زمینه‌ای که کاربر می‌خواهد در آن پیشرفت کند: $focusArea
وضعیت شغلی/تحصیلی کاربر: $occupation
گروه سنی کاربر: $ageGroup
روزهایی که کاربر معمولاً سرش شلوغ است (ترجیحاً این روزها را انتخاب نکن): $busyDaysList
توضیحات تکمیلی که خودِ کاربر نوشته (مهم‌ترین منبع برای شخصی‌سازی، اگر معنادار بود حتماً استفاده کن): $extraDetailsText

عادت‌های موجود در برنامه (فقط از بین همین‌ها انتخاب کن):
$habitsList

قوانین پاسخ:
1. فقط و فقط یک آبجکت JSON خام برگردان، بدون هیچ توضیح اضافه و بدون backtick.
2. عنوان (customTitle) باید شامل یک فعالیت مشخص، عینی و قابل‌اجرا باشد، نه فقط یک عبارت انگیزشی کلی.
   مثال خوب: «پیاده‌روی ۲۰ دقیقه‌ای عصرگاهی»، «۱۰ دقیقه یوگای صبحگاهی»، «مطالعه ۱۵ صفحه از یک کتاب غیردرسی».
   مثال بد (رد می‌شود): «انرژی بی‌نهایت»، «قدرت درونی»، «حرکت روزانه».
3. targetDays را متناسب با سختی و نوع فعالیت انتخابی و سن/شرایط کاربر تعیین کن؛ حداقل 21. برای فعالیت‌های سبک روزانه معمولاً بین 21 تا 30 روز، برای عادت‌هایی که نیاز به تغییر بزرگ‌تر یا سخت‌تر دارند بین 45 تا 66 روز مناسب‌تر است.
4. selectedDays را ترجیحاً از بین روزهایی انتخاب کن که کاربر گفته سرش شلوغ نیست، و با توجه به توضیحات تکمیلی کاربر تنظیمش کن.
5. reminderTime را با فرمت دقیق "HH:mm" (۲۴ ساعته، مثلاً "07:00" یا "21:30") بر اساس نوع فعالیت انتخاب کن (مثلاً مدیتیشن صبح زود، کتاب‌خوانی قبل خواب، ورزش عصر یا بر اساس توضیحات کاربر).
6. یک فیلد reason هم اضافه کن: ۲ تا ۳ جمله‌ی کوتاه فارسی که توضیح بدهد چرا این فعالیت، این تعداد روز، این روزها، و مخصوصاً چرا این ساعت یادآور را برای همین کاربر انتخاب کردی (با اشاره به سن، شغل/تحصیلات یا توضیحات کاربر).
7. ساختار دقیق JSON باید این باشد:
{"habitId": <یکی از idهای بالا>, "customTitle": "<فعالیت مشخص>", "targetDays": <عدد>, "selectedDays": [<چند مورد از "SAT","SUN","MON","TUE","WED","THU","FRI">], "reminderTime": "<HH:mm>", "reason": "<۲ تا ۳ جمله>"}
        """.trim()

    }

    data class HabitAnalysisData(

        val userHabitId: Int,

        val title: String,

        val targetDays: Int,

        val currentStreak: Int,

        val overallSuccessRate: Int,

        val weekdayBreakdown: String

    )

    fun buildPersonalizedAnalysisPrompt(

        habits: List<HabitAnalysisData>,

        dailyGrid: String

    ): String {

        val habitsList =
            habits.joinToString(separator = "\n\n") {

                """
شناسه: ${it.userHabitId}
عنوان عادت: ${it.title}
تعداد روز هدف: ${it.targetDays}
استریک فعلی: ${it.currentStreak}
نرخ موفقیت کلی: ${it.overallSuccessRate}٪
عملکرد به تفکیک روز هفته (تعداد انجام‌شده از تعداد برنامه‌ریزی‌شده): ${it.weekdayBreakdown}
                """.trim()

            }

        return """
تو یک مربی حرفه‌ای عادت‌سازی هستی که به یک کاربر ایرانی کمک می‌کنی رفتارش را عمیق‌تر بشناسد. کارت این نیست که فقط آمار را تکرار کنی (کاربر خودش می‌تواند درصدها را ببیند)، بلکه باید الگوهای پنهان، ارتباط بین عادت‌های مختلف، و یک راهکار رفتاری واقعاً کاربردی پیدا کنی که با نگاه سطحی به یک عادت به‌تنهایی قابل کشف نیست.

توجه فرهنگی مهم و اجباری: کاربر ایرانی و فارسی‌زبان است. هفته‌ی ایرانی از شنبه آغاز می‌شود و ترتیب دقیق روزهای هفته این است: شنبه، یکشنبه، دوشنبه، سه‌شنبه، چهارشنبه، پنجشنبه، جمعه. یعنی شنبه اولین روز هفته است، نه دوشنبه. روزهای تعطیل رسمی در ایران پنجشنبه و جمعه هستند، نه شنبه و یکشنبه. در تحلیل خود هرگز از تقویم میلادی/غربی (که هفته را از دوشنبه یا یکشنبه شروع می‌کند) استفاده نکن.

اطلاعات کلی هر عادت:
$habitsList

جدول روزانه‌ی انجام/عدم‌انجام هر عادت در ۲۱ روز اخیر («✓» یعنی انجام‌شده، «✗» یعنی برنامه‌ریزی‌شده ولی انجام‌نشده، «—» یعنی آن روز اصلاً برای آن عادت برنامه‌ریزی نشده بوده؛ از این جدول برای پیدا کردن ارتباط بین عادت‌ها استفاده کن):
$dailyGrid

قوانین پاسخ:
1. فقط و فقط یک آبجکت JSON خام برگردان، بدون هیچ توضیح اضافه و بدون backtick.
2. تحلیل باید فراتر از توصیف آمار باشد؛ دنبال ارتباط بین عادت‌ها (مثلاً وقتی عادت X انجام شده، عادت Y هم بیشتر انجام شده)، الگوهای پنهان در روزهای هفته، یا روند کلی رفتار کاربر بگرد.
3. actionSuggestion باید یک تکنیک رفتاری مشخص و عملی باشد (مثل زنجیره‌کردن عادت‌ها با هم، تغییر ترتیب انجامشان، تغییر زمان انجام، یا کوچک‌تر کردن هدف)، نه یک توصیه‌ی کلی مثل «سعی کن منظم‌تر باشی».
4. لحن باید مثل یک مربی دلسوز و حرفه‌ای باشد، با جمله‌بندی روان و طبیعی فارسی، نه یک گزارش خشک آماری و نه ترجمه‌ی ماشینی.
5. ساختار دقیق JSON:
{"priorityFocus": "<یک جمله: مهم‌ترین نکته یا اولویت الان>", "analysis": "<۳ تا ۵ جمله تحلیل عمیق و روایت‌گونه>", "actionSuggestion": "<۱ تا ۲ جمله پیشنهاد رفتاری عملی و مشخص>"}
        """.trim()

    }

}